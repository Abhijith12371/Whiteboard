export function searchIcons(query: string, catalog = ICON_CATALOG): IconAsset[] {
  const q = query.trim().toLowerCase()
  if (!q) return catalog
  return catalog.filter((icon) => icon.keywords.some((k) => k.includes(q)) || icon.name.toLowerCase().includes(q))
}
